import React, { useMemo, useState, useRef, useEffect, useCallback } from 'react';
import { useNavigate } from 'react-router-dom';
import { useForm, useFieldArray, Controller } from 'react-hook-form';
import { zodResolver } from '@hookform/resolvers/zod';
import { z } from 'zod';
import {
  Utensils,
  Info,
  Search,
  Hash,
  Component,
  Soup,
  Flame,
  Beef,
  Droplet,
  Wheat,
  Weight,
  Tag,
  Save,
  ChevronDown,
} from 'lucide-react';
import {
  DndContext,
  closestCenter,
  PointerSensor,
  useSensor,
  useSensors,
  DragEndEvent,
  DragStartEvent,
  DragOverlay,
} from '@dnd-kit/core';
import { SortableContext, verticalListSortingStrategy } from '@dnd-kit/sortable';
import type { Meal, MealData, MealPlanItem } from '../../types';
import useProductStore from '../../stores/useProductStore';
import useDishStore from '../../stores/useDishStore';
import type { Product, Dish, DishProduct } from '../../types';
import useCategoryStore from '../../stores/useCategoryStore';
import useMealTypesStore from '../../stores/useMealTypesStore';
import Textarea from '../../ui/Textarea';
import Input from '../../ui/Input';
import Button from '../../ui/Button';
import SortableItemComponent from './SortableItem';
import DropdownSelect from '../../ui/DropdownSelect';
import { calculateNutrition, isMealNameUnique } from './mealFormUtils';
import { useMealStore } from '../../stores/useMealStore';
import ItemContent from './ItemContent';

interface MealFormProps {
  meal?: Meal | null;
  onSubmit: (data: MealData) => void;
  onCancel: () => void;
  /** Auto-generated name for new meals */
  autoGeneratedName?: string;
  /** If true, focus name input on mount */
  focusName?: boolean;
  /** Open sections state for preserving collapsible section states */
  openSections?: string[];
  /** Callback for toggling section open/closed state */
  onToggleSection?: (sectionId: string) => void;
}

// --- CollapsibleSection ---
interface CollapsibleSectionProps {
  id: string;
  title: string;
  icon: React.ReactNode;
  children: React.ReactNode;
  isOpen: boolean;
  onToggle: (id: string) => void;
  actionButton?: React.ReactNode;
  summaryContent?: React.ReactNode;
  headerContent?: React.ReactNode;
  gradientFrom?: string;
  gradientVia?: string;
  gradientTo?: string;
  className?: string;
}

const CollapsibleSection: React.FC<CollapsibleSectionProps> = ({
  id,
  title,
  icon,
  children,
  isOpen,
  onToggle,
  actionButton,
  summaryContent,
  headerContent,
  gradientFrom = 'from-blue-500/5',
  gradientVia = 'via-purple-500/5',
  gradientTo = 'to-pink-500/5',
  className = '',
}) => {
  return (
    <div
      className={`bg-gradient-to-br ${gradientFrom} ${gradientVia} ${gradientTo} border border-border rounded-xl overflow-visible ${className}`}
    >
      <div
        className="flex items-center justify-between gap-3 p-6 cursor-pointer hover:bg-muted/50 transition-colors"
        onClick={() => onToggle(id)}
      >
        <div className="flex items-center gap-3 flex-1 min-w-0">
          <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-primary/10 flex-shrink-0">
            {icon}
          </div>
          <h2 className="text-lg font-semibold truncate">{title}</h2>
          {summaryContent && <div className="ml-2 flex-shrink-0">{summaryContent}</div>}
        </div>
        <div className="flex items-center gap-2 min-w-[200px] justify-end">
          {actionButton}
          {headerContent}
        </div>
      </div>
      {isOpen && <div className="p-6 pt-0">{children}</div>}
    </div>
  );
};

const MealForm: React.FC<MealFormProps> = ({
  meal,
  onSubmit,
  onCancel,
  autoGeneratedName,
  focusName = false,
  openSections,
  onToggleSection,
}) => {
  const { products } = useProductStore();
  const { dishes } = useDishStore();
  const { categories } = useCategoryStore();
  const { meals } = useMealStore();
  const { mealTypes } = useMealTypesStore();
  const navigate = useNavigate();

  // Create validation schema without uniqueness check (only basic validation)
  const validationSchema = useMemo(() => {
    return z.object({
      name: z.string().optional(),
      description: z.string().optional(),
      mealTypeId: z.string().optional(),
      items: z
        .array(
          z.object({
            instanceId: z.string(),
            type: z.enum(['product', 'dish']),
            itemId: z.number(),
            weight: z.number().min(1, 'Вес должен быть больше 0').optional(),
          })
        )
        .min(1, 'Приём пищи должен содержать хотя бы один продукт или блюдо'),
    });
  }, []);

  type MealFormValues = z.infer<typeof validationSchema>;
  const [searchQuery, setSearchQuery] = useState('');
  const [isFocused, setIsFocused] = useState(false);
  const [activeId, setActiveId] = useState<string | null>(null);
  const [showAddMenu, setShowAddMenu] = useState(false);
  const [dropdownPosition, setDropdownPosition] = useState({ top: 0, left: 0, width: 0 });
  const [showHeaderNutrition, setShowHeaderNutrition] = useState(false);
  const nameInputRef = useRef<HTMLInputElement | null>(null);
  const searchInputRef = useRef<HTMLDivElement>(null);
  const dropdownRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (focusName && nameInputRef.current) {
      // small timeout to ensure input is mounted
      setTimeout(() => nameInputRef.current && nameInputRef.current.focus(), 50);
    }
  }, [focusName]);

  const handleEditItem = (item: { type: 'product' | 'dish'; itemId: number }) => {
    if (item.type === 'product') {
      const product = products.find((p) => p.id === item.itemId);
      if (product) {
        navigate(`/products?selectedId=${product.id}`);
      }
    } else if (item.type === 'dish') {
      const dish = dishes.find((d) => d.id === item.itemId);
      if (dish) {
        navigate(`/dishes?selectedId=${dish.id}`);
      }
    }
  };

  const {
    control,
    formState: { errors },
    watch,
    setValue,
    clearErrors,
  } = useForm<MealFormValues>({
    resolver: zodResolver(validationSchema),
    defaultValues: {
      name: meal?.name || '',
      description: meal?.description || '',
      mealTypeId: meal?.mealTypeId ? String(meal.mealTypeId) : '',
      items: meal?.items || [],
    },
  });

  // Set auto-generated name when component mounts (only for new meals)
  useEffect(() => {
    if (!meal && autoGeneratedName) {
      setValue('name', autoGeneratedName);
    }
  }, [meal, autoGeneratedName, setValue]);

  const { fields, append, remove, move, update } = useFieldArray({ control, name: 'items' });
  const watchItems = watch('items');

  const [validationErrors, setValidationErrors] = useState<{ name?: string; items?: string }>({});

  useEffect(() => {
    if (validationErrors.items && (watchItems?.length || 0) > 0) {
      setValidationErrors((prev) => ({ ...prev, items: undefined }));
      clearErrors('items');
    }
  }, [watchItems?.length, validationErrors.items, clearErrors, setValidationErrors]);

  useEffect(() => {
    if (showAddMenu && searchInputRef.current) {
      const rect = searchInputRef.current.getBoundingClientRect();
      const scrollTop = window.pageYOffset || document.documentElement.scrollTop;
      const scrollLeft = window.pageXOffset || document.documentElement.scrollLeft;

      setDropdownPosition({
        top: rect.bottom + scrollTop + 8,
        left: rect.left + scrollLeft,
        width: rect.width,
      });
    }
  }, [showAddMenu]);

  useEffect(() => {
    if (!showAddMenu) return;

    const handlePositionUpdate = () => {
      if (searchInputRef.current) {
        const rect = searchInputRef.current.getBoundingClientRect();
        const scrollTop = window.pageYOffset || document.documentElement.scrollTop;
        const scrollLeft = window.pageXOffset || document.documentElement.scrollLeft;

        setDropdownPosition({
          top: rect.bottom + scrollTop + 8,
          left: rect.left + scrollLeft,
          width: rect.width,
        });
      }
    };

    window.addEventListener('scroll', handlePositionUpdate, true);
    window.addEventListener('resize', handlePositionUpdate);

    return () => {
      window.removeEventListener('scroll', handlePositionUpdate, true);
      window.removeEventListener('resize', handlePositionUpdate);
    };
  }, [showAddMenu]);

  useEffect(() => {
    const handleClickOutside = (event: MouseEvent) => {
      const target = event.target as Node;
      const isInsideSearchArea = searchInputRef.current?.contains(target);
      const isInsideDropdown = dropdownRef.current?.contains(target);

      if (!isInsideSearchArea && !isInsideDropdown) {
        setShowAddMenu(false);
        setSearchQuery('');
      }
    };

    const handleEscapeKey = (event: KeyboardEvent) => {
      if (event.key === 'Escape') {
        setShowAddMenu(false);
        setSearchQuery('');
      }
    };

    if (showAddMenu) {
      const timer = setTimeout(() => {
        document.addEventListener('mousedown', handleClickOutside);
        document.addEventListener('keydown', handleEscapeKey);
        document.body.classList.add('dropdown-open');
      }, 100);

      return () => {
        clearTimeout(timer);
        document.removeEventListener('mousedown', handleClickOutside);
        document.removeEventListener('keydown', handleEscapeKey);
        document.body.classList.remove('dropdown-open');
      };
    }
  }, [showAddMenu]);

  const filteredProducts = useMemo(() => {
    const query = searchQuery.toLowerCase();

    return products
      .filter((product) => {
        // Search by product name
        const nameMatch = product.name.toLowerCase().includes(query);

        // Search by category name
        let categoryMatch = false;
        if (product.categoryId) {
          const category = categories.find((cat) => cat.id === product.categoryId);
          if (category) {
            categoryMatch = category.name.toLowerCase().includes(query);
          }
        }

        return nameMatch || categoryMatch;
      })
      .sort((a, b) => a.name.localeCompare(b.name));
  }, [products, categories, searchQuery]);

  const filteredDishes = useMemo(() => {
    return dishes
      .filter((dish) => dish.name.toLowerCase().includes(searchQuery.toLowerCase()))
      .sort((a, b) => a.name.localeCompare(b.name));
  }, [dishes, searchQuery]);

  const activeItem = useMemo(() => {
    return activeId ? watchItems.find((item, idx) => fields[idx]?.id === activeId) : null;
  }, [activeId, watchItems, fields]);

  // Helper function to calculate item weight consistently
  const calculateItemWeight = (item: MealPlanItem, products: Product[], dishes: Dish[]): number => {
    if (item.type === 'product') {
      return item.weight || 0;
    } else if (item.type === 'dish') {
      const dish = dishes.find((d) => d.id === item.itemId);
      if (dish) {
        return Number(
          dish.products.reduce((sum: number, dp: DishProduct) => sum + Number(dp.weight), 0)
        );
      }
    }
    return 0;
  };

  // Calculate total weight including dishes
  const totalWeight = useMemo(() => {
    return watchItems.reduce((total, item) => {
      return total + calculateItemWeight(item as MealPlanItem, products, dishes);
    }, 0);
  }, [watchItems, products, dishes]);

  const totalNutrition = useMemo(() => {
    let calories = 0,
      proteins = 0,
      fats = 0,
      carbs = 0;
    watchItems.forEach((item) => {
      const nutrition = calculateNutrition(item as MealPlanItem, products, dishes);
      if (nutrition) {
        calories += nutrition.calories;
        proteins += nutrition.proteins;
        fats += nutrition.fats;
        carbs += nutrition.carbs;
      }
    });
    return {
      calories: Math.round(calories),
      proteins: Math.round(proteins * 10) / 10,
      fats: Math.round(fats * 10) / 10,
      carbs: Math.round(carbs * 10) / 10,
    };
  }, [watchItems, products, dishes]);

  const handleAddItem = (itemId: number, type: 'product' | 'dish') => {
    let defaultWeight = 100;
    if (type === 'product') {
      const product = products.find((p) => p.id === itemId);
      defaultWeight =
        product && product.portions.length > 0 ? Number(product.portions[0].weight) : 100;
    } else if (type === 'dish') {
      const dish = dishes.find((d) => d.id === itemId);
      if (dish) {
        defaultWeight = Number(dish.products.reduce((sum, p) => sum + Number(p.weight), 0) || 100);
      }
    }
    append({
      instanceId: `${type}-${Date.now()}`,
      type,
      itemId,
      weight: Number(defaultWeight),
    });
    setShowAddMenu(false);
    setSearchQuery('');
  };

  const updateItemWeight: (index: number, weight: number) => void = (
    index: number,
    weight: number
  ) => {
    if (watchItems[index].type === 'product') {
      const numericWeight = Number(weight);
      const updatedItem = { ...watchItems[index], weight: numericWeight };
      update(index, updatedItem);
    }
  };

  const sensors = useSensors(
    useSensor(PointerSensor, {
      activationConstraint: {
        distance: 3, // Уменьшаем расстояние для более легкого начала перетаскивания
      },
    })
  );

  const handleDragStart = (event: DragStartEvent) => {
    setActiveId(event.active.id as string);
  };

  const handleDragEnd = (event: DragEndEvent) => {
    const { active, over } = event;
    setActiveId(null);
    if (over && active.id !== over.id) {
      const oldIndex = fields.findIndex((item) => item.id === active.id);
      const newIndex = fields.findIndex((item) => item.id === over.id);
      move(oldIndex, newIndex);
    }
  };

  const processSubmit = useCallback(() => {
    const name = watch('name');
    const description = watch('description');
    const mealTypeId = watch('mealTypeId');
    const mealTypeIdNumber = mealTypeId && mealTypeId !== '' ? Number(mealTypeId) : undefined;

    // Clear previous validation errors
    setValidationErrors({});

    // Validate name
    if (!name || !name.trim()) {
      setValidationErrors((prev) => ({
        ...prev,
        name: 'Название приёма пищи не может быть пустым',
      }));
      return;
    }

    // Check uniqueness before submitting
    if (name && !isMealNameUnique(name, meals, meal?.id)) {
      setValidationErrors((prev) => ({
        ...prev,
        name: 'Приём пищи с таким названием уже существует',
      }));
      return;
    }

    if (watchItems.length === 0) {
      setValidationErrors((prev) => ({
        ...prev,
        items: 'Приём пищи должен содержать хотя бы один продукт или блюдо',
      }));
      return;
    }

    const mealData: MealData = {
      name: name.trim(),
      description,
      mealTypeId: mealTypeIdNumber,
      items: watchItems.map(({ instanceId: _, ...item }) => item) as MealPlanItem[],
    };
    onSubmit(mealData);
  }, [watch, watchItems, onSubmit, meals, meal?.id, setValidationErrors]);

  // Use the passed openSections prop or default values
  const currentOpenSections = openSections ?? ['basic-info', 'composition'];
  const isBasicInfoOpen = currentOpenSections.includes('basic-info');
  const isCompositionOpen = currentOpenSections.includes('composition');

  // Provide a default function if onToggleSection is not provided
  const handleToggleSection =
    onToggleSection ??
    (() => {
      // Default implementation - do nothing
    });

  return (
    <div className="space-y-6">
      <CollapsibleSection
        id="basic-info"
        title="Основная информация"
        icon={<Info className="w-4 h-4 text-primary" />}
        isOpen={isBasicInfoOpen}
        onToggle={handleToggleSection}
        actionButton={
          <div className="flex items-center gap-2 min-w-[280px] justify-end">
            <Button
              type="button"
              variant="ghost"
              onClick={(e) => {
                e.stopPropagation(); // Предотвращаем распространение клика на CollapsibleSection
                onCancel();
              }}
            >
              Отмена
            </Button>
            <Button
              type="button"
              variant="primary"
              onClick={(e) => {
                e.stopPropagation(); // Предотвращаем распространение клика на CollapsibleSection
                processSubmit();
              }}
              icon={Save}
              size="icon"
            >
              {/* Empty - only icon */}
            </Button>
          </div>
        }
        gradientFrom="from-blue-500/5"
        gradientVia="via-purple-500/5"
        gradientTo="to-pink-500/5"
      >
        <div className="space-y-4 pt-4">
          <Controller
            name="name"
            control={control}
            render={({ field }) => (
              <div className="space-y-1">
                <label className="block text-sm font-medium text-foreground mb-2">Название *</label>
                <Input
                  {...field}
                  ref={nameInputRef}
                  type="text"
                  placeholder={
                    meal ? 'Например, Завтрак, Обед, Ужин...' : 'Приём пищи (можно изменить)'
                  }
                  autoFocus
                  error={validationErrors.name || errors.name?.message}
                />
              </div>
            )}
          />
          <Controller
            name="mealTypeId"
            control={control}
            render={({ field }) => (
              <DropdownSelect
                label="Тип"
                icon={Tag}
                options={[
                  { value: '', label: 'Не указан' },
                  ...mealTypes.map((type) => ({
                    value: String(type.id),
                    label: type.name,
                  })),
                ]}
                value={String(field.value || '')}
                onChange={(val) => {
                  field.onChange(val);
                }}
                placeholder="Выберите тип приёма пищи"
              />
            )}
          />
          <Controller
            name="description"
            control={control}
            render={({ field }) => (
              <Textarea
                {...field}
                label="Описание"
                rows={3}
                placeholder="Добавьте заметки или комментарии..."
              />
            )}
          />
        </div>
      </CollapsibleSection>

      <CollapsibleSection
        id="composition"
        title="Состав"
        icon={<Utensils className="w-4 h-4 text-green-600" />}
        isOpen={isCompositionOpen}
        onToggle={handleToggleSection}
        summaryContent={
          watchItems.length > 0 && (
            <span className="flex items-center gap-1.5 text-sm text-muted-foreground">
              <Hash className="w-3.5 h-3.5" />
              {watchItems.length}
            </span>
          )
        }
        headerContent={
          watchItems.length > 0 && (
            <button
              onClick={(e) => {
                e.stopPropagation();
                setShowHeaderNutrition(!showHeaderNutrition);
              }}
              className="flex items-center gap-1.5 px-3 h-9 bg-muted/50 rounded-md border border-border hover:bg-muted transition-all"
            >
              {showHeaderNutrition ? (
                <>
                  <ChevronDown className="w-3.5 h-3.5 text-muted-foreground -rotate-90 transition-transform" />
                  <div className="flex items-center gap-2 text-sm">
                    <div className="flex items-center gap-1">
                      <Flame className="w-4 h-4 text-orange-600" />
                      <span className="font-semibold text-orange-600">
                        {totalNutrition.calories}
                      </span>
                    </div>
                    <div className="w-px h-4 bg-border" />
                    <div className="flex items-center gap-1">
                      <Beef className="w-4 h-4 text-blue-600" />
                      <span className="font-semibold text-blue-600">{totalNutrition.proteins}</span>
                    </div>
                    <div className="w-px h-4 bg-border" />
                    <div className="flex items-center gap-1">
                      <Droplet className="w-4 h-4 text-yellow-600" />
                      <span className="font-semibold text-yellow-600">{totalNutrition.fats}</span>
                    </div>
                    <div className="w-px h-4 bg-border" />
                    <div className="flex items-center gap-1">
                      <Wheat className="w-4 h-4 text-green-600" />
                      <span className="font-semibold text-green-600">{totalNutrition.carbs}</span>
                    </div>
                  </div>
                  <div className="w-px h-4 bg-border" />
                  <div className="flex items-center gap-1">
                    <Weight className="w-4 h-4 text-muted-foreground" />
                    <span className="font-semibold text-muted-foreground text-sm">
                      {totalWeight}
                    </span>
                  </div>
                </>
              ) : (
                <>
                  <ChevronDown className="w-3.5 h-3.5 text-muted-foreground rotate-90 transition-transform" />
                  <div className="flex items-center gap-1">
                    <Weight className="w-4 h-4 text-muted-foreground" />
                    <span className="font-semibold text-muted-foreground text-sm">
                      {totalWeight}
                    </span>
                  </div>
                </>
              )}
            </button>
          )
        }
        gradientFrom="from-orange-500/5"
        gradientVia="via-yellow-500/5"
        gradientTo="to-green-500/5"
        className="[background:var(--color-meal-composition-gradient)] border border-border"
      >
        <div className="relative mb-4" ref={searchInputRef}>
          <div className="relative">
            <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-muted-foreground pointer-events-none z-10" />
            <Input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              onFocus={() => {
                setIsFocused(true);
                setShowAddMenu(true);
              }}
              onBlur={() => setIsFocused(false)}
              placeholder={!isFocused ? 'Найти продукт или блюдо...' : ''}
              className={!isFocused && !searchQuery ? 'text-center pl-10' : 'text-left pl-10'}
            />
          </div>

          {showAddMenu && searchInputRef.current && (
            <div
              ref={dropdownRef}
              className="fixed-dropdown-container bg-card border border-border rounded-lg shadow-2xl overflow-hidden"
              style={{
                top: `${dropdownPosition.top}px`,
                left: `${dropdownPosition.left}px`,
                width: `${dropdownPosition.width}px`,
                maxHeight: '300px',
              }}
              onWheel={(e) => {
                e.stopPropagation();
                e.preventDefault();
                const scrollContainer = dropdownRef.current?.querySelector(
                  '.absolute-dropdown-scrollbar'
                ) as HTMLElement;
                if (scrollContainer && e instanceof WheelEvent) {
                  scrollContainer.scrollTop += e.deltaY;
                }
              }}
              onTouchMove={(e) => {
                e.stopPropagation();
                e.preventDefault();
                const scrollContainer = dropdownRef.current?.querySelector(
                  '.absolute-dropdown-scrollbar'
                ) as HTMLElement;
                if (scrollContainer) {
                  // Check if this is a wheel event with deltaY property
                  if ('deltaY' in e && typeof e.deltaY === 'number') {
                    scrollContainer.scrollTop += e.deltaY;
                  }
                }
              }}
            >
              <div
                className="p-2 absolute-dropdown-scrollbar"
                tabIndex={0}
                onTouchMove={(e) => {
                  e.stopPropagation();
                }}
              >
                {filteredDishes.length === 0 && filteredProducts.length === 0 ? (
                  <div className="px-3 py-8 text-center text-sm text-muted-foreground">
                    Ничего не найдено
                  </div>
                ) : (
                  <>
                    {filteredDishes.length > 0 && (
                      <div className="mb-2">
                        <div className="px-3 py-1.5 text-xs font-semibold text-muted-foreground uppercase flex items-center gap-2">
                          <Soup className="w-3.5 h-3.5 text-orange-500" />
                          Блюда ({filteredDishes.length})
                        </div>
                        {filteredDishes.map((dish) => (
                          <button
                            key={dish.id}
                            type="button"
                            onClick={() => handleAddItem(dish.id, 'dish')}
                            className="search-menu-item"
                          >
                            <Soup className="w-3.5 h-3.5 text-orange-500" />
                            {dish.name}
                          </button>
                        ))}
                      </div>
                    )}
                    {filteredProducts.length > 0 && (
                      <div>
                        <div className="px-3 py-1.5 text-xs font-semibold text-muted-foreground uppercase flex items-center gap-2">
                          <Component className="w-3.5 h-3.5 text-blue-500" />
                          Продукты ({filteredProducts.length})
                        </div>
                        {filteredProducts.map((product) => {
                          const category = product.categoryId
                            ? categories.find((cat) => cat.id === product.categoryId)
                            : null;
                          return (
                            <button
                              key={product.id}
                              type="button"
                              onClick={() => handleAddItem(product.id, 'product')}
                              className="search-menu-item"
                            >
                              <Component className="w-3.5 h-3.5 text-blue-500" />
                              <span className="flex-1">{product.name}</span>
                              {category && (
                                <span className="text-muted-foreground text-xs flex items-center gap-1">
                                  {category.emoji} {category.name}
                                </span>
                              )}
                            </button>
                          );
                        })}
                      </div>
                    )}
                  </>
                )}
              </div>
            </div>
          )}
        </div>

        <div className="space-y-3 pt-4">
          <DndContext
            sensors={sensors}
            collisionDetection={closestCenter}
            onDragStart={handleDragStart}
            onDragEnd={handleDragEnd}
          >
            <SortableContext items={fields.map((f) => f.id)} strategy={verticalListSortingStrategy}>
              {fields.map((field, index) => (
                <SortableItemComponent
                  key={field.id}
                  id={field.id}
                  index={index}
                  item={watchItems[index] as MealPlanItem}
                  products={products}
                  dishes={dishes}
                  onRemove={remove}
                  onUpdateWeight={updateItemWeight}
                  onEditItem={handleEditItem}
                />
              ))}
            </SortableContext>

            <DragOverlay>
              {activeId && activeItem ? (
                <div
                  className={`rounded-xl p-3 shadow-2xl z-50 border ${
                    (activeItem as MealPlanItem).type === 'product'
                      ? '[background:var(--color-product-gradient)] border border-[#3b82f6] shadow-[0_4px_8px_rgba(0,0,0,0.2),0_2px_4px_rgba(0,0,0,0.15)]'
                      : '[background:var(--color-dish-gradient)] border border-[#f59e0b] shadow-[0_4px_8px_rgba(0,0,0,0.2),0_2px_4px_rgba(0,0,0,0.15)]'
                  }`}
                >
                  <ItemContent
                    item={activeItem as MealPlanItem}
                    products={products}
                    dishes={dishes}
                    showActions={false}
                  />
                </div>
              ) : null}
            </DragOverlay>

            <>
              {watchItems.length === 0 && (
                <div className="text-center py-8 text-muted-foreground">
                  <Utensils className="w-12 h-12 mx-auto mb-3 opacity-50" />
                  <p className="text-sm">Добавьте продукты или блюда</p>
                  <p className="text-xs mt-1">Перетаскивайте элементы для изменения порядка</p>
                </div>
              )}
            </>
          </DndContext>
        </div>
      </CollapsibleSection>
    </div>
  );
};

export default MealForm;
